function out = tsx_text_varsbc(x, digits)
%TSX_TEXT_VARSBC Text output of varsbc (print.tsx_varsbc in R).
import tsexplorer.internal.*
if isempty(digits)
    digits = 4;
end
b = x.best;
out = tsx_cat_block(["Identification Criteria"; "Series " + tsx_series_label(x.series)], ...
    ["AICc(" + b.aicc + "): Corrected Akaike Information Criterion"; ...
     "SBC(" + b.sbc + "): Schwarz Information Criterion"; ...
     "HQC(" + b.hqc + "): Hannan and Quinn Criterion"; ...
     "CHI: Likelihood ratio test of order k vs order k-1"], ...
    tsx_format_table(x.table, [0, repmat(digits, 1, 5)], [], ...
        ["Lag", "AICc", "SBC", "HQC", "CHI", "P-CHI"]));
end
