function out = tsx_text_stdmean(x, digits)
%TSX_TEXT_STDMEAN Text output of stdmean (print.tsx_stdmean in R).
if isempty(digits)
    digits = 4;
end
out = tsexplorer.internal.tsx_cat_block( ...
    "Series " + x.series + ": dispersion vs location by groups of " + x.call.s, ...
    sprintf('Least squares line: intercept %.4f, slope %.4f', x.coef.intercept, x.coef.slope), ...
    tsexplorer.internal.tsx_format_table(x.table, [0, digits, digits], [], ...
        ["Group", "Location", "Dispersion"]));
end
