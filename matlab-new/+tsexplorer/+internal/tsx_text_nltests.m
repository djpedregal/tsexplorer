function out = tsx_text_nltests(x, digits)
%TSX_TEXT_NLTESTS Text output of nltests (print.tsx_nltests in R).
import tsexplorer.internal.*
if isempty(digits)
    digits = 4;
end
t = x.table;
lines = tsx_format_table({t.lag, t.acf, tsx_signif_marks(t.acf ./ t.se_acf), t.q_mll, t.p_mll, ...
    t.pacf, tsx_signif_marks(t.pacf ./ t.se_pacf), t.q_mt, t.p_mt, t.d_pr, t.p_pr}, ...
    [0, digits, 0, digits, digits, digits, 0, digits, digits, digits, digits], [], ...
    ["Lag", "SACF", "", "MLL", "P-value", "SPACF", "", "MT", "P-value", "PR", "P-value"]);
out = tsx_cat_block("Non-Linearity Tests", ...
    ["MLL: McLeod & Li (1983) Test"; "MT:  Monti (1994) Test"; ...
     "PR:  Pe" + char(241) + "a & Rodriguez (2002) Test"; "H0:  Process is Linear"; ...
     "Series " + x.series], lines);
end
