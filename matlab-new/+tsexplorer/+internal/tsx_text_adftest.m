function out = tsx_text_adftest(x, digits)
%TSX_TEXT_ADFTEST Text output of adftest (print.tsx_adftest in R).
import tsexplorer.internal.*
if isempty(digits)
    digits = 4;
end
multi = numel(unique(x.none.series)) > 1;
rn = @(d) row_names(d, multi);
drop_series = @(d) d(:, ~strcmp(d.Properties.VariableNames, 'series'));
out = tsx_cat_block("Augmented Dickey-Fuller Tests (NO CONSTANT, NO TREND)", ...
    ["T-Test for z(t-1) is H0: Rho= 1 (Series is integrated)"; ...
     "P values are approximate based on tables"], ...
    tsx_format_table(drop_series(x.none), [0, digits, digits, digits], rn(x.none), ...
        ["Lags", "z(t-1)", "T-Test", "P-value"]));
out = [out; ""; tsx_cat_block("Augmented Dickey-Fuller Tests (CONSTANT, NO TREND)", ...
    ["T-Test for z(t-1) is H0: Rho= 1 (Series is integrated)"; ...
     "F-Test (Phi1) is for H0: Rho= 1 and Ct= 0"], ...
    tsx_format_table(drop_series(x.const), [0, repmat(digits, 1, 7)], rn(x.const), ...
        ["Lags", "z(t-1)", "T-Test", "P-value", "Ct", "T-Test", "F-Test", "P-value"]))];
out = [out; ""; tsx_cat_block("Augmented Dickey-Fuller Tests (CONSTANT AND TREND)", ...
    ["T-Test for z(t-1) is H0: Rho= 1 (Series is integrated)"; ...
     "F-Test (Phi3) is for H0: Rho= 1 and D= 0"], ...
    tsx_format_table(drop_series(x.trend), [0, repmat(digits, 1, 9)], rn(x.trend), ...
        ["Lags", "z(t-1)", "T-Test", "P-value", "Ct", "T-Test", "D", "T-Test", "F-Test", ...
         "P-value"]))];
end

function r = row_names(d, multi)
if multi
    r = d.series;
else
    r = [];
end
end
