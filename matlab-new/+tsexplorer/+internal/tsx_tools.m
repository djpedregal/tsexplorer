function t = tool(id, label, group, fun, series, plot, nav, multi, series_in_plot, options)
t = struct('id', string(id), 'label', string(label), 'group', string(group), 'fun', fun, ...
    'series', string(series), 'plot', plot, 'nav', string(nav), 'multi', multi, ...
    'series_in_plot', series_in_plot, 'options', options);
end

function op = opt(name, label, type, varargin)
% empty struct array (no options) when called without arguments
op = struct('name', {}, 'label', {}, 'type', {}, 'min', {}, 'max', {}, ...
    'choice_labels', {}, 'choice_values', {});
if nargin == 0
    return
end
op(1).name = string(name);
op.label = string(label);
op.type = string(type);
op.min = [];
op.max = [];
op.choice_labels = strings(0);
op.choice_values = [];
for k = 1:2:numel(varargin)
    switch varargin{k}
        case "min"
            op.min = varargin{k + 1};
        case "max"
            op.max = varargin{k + 1};
        case "choices"
            op.choice_labels = varargin{k + 1}{1};
            op.choice_values = varargin{k + 1}{2};
    end
end
end
