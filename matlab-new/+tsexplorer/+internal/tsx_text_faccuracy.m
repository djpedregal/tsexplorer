function out = tsx_text_faccuracy(x, digits)
%TSX_TEXT_FACCURACY Text output of faccuracy (print.tsx_faccuracy in R). The
%   columns that are all missing (interval measures without stdpy, MASE
%   without in-sample data) are not shown.
import tsexplorer.internal.*
if isempty(digits)
    digits = 3;
end
t = x.table;
keep = varfun(@(v) ~all(isnan(v)), t, 'OutputFormat', 'uniform');
t = t(:, keep);
lv = x.call.level;
keys = ["n", "bias", "mae", "bias_mae", "rmse", "mase", "coverage", "range", "mis", ...
    "pinball_lower", "pinball_upper"];
notes = ["", "bias:          Mean Error (F - y)", "mae:           Mean Absolute Error", ...
    "bias+mae:      |bias| + mae", "rmse:          Root Mean Squared Error", ...
    "mase:          Mean Absolute Scaled Error (mae out sample / mae in sample)", ...
    "coverage:      proportion of actual values inside the intervals (nominal " + ...
        tsx_format_num(lv) + ")", ...
    "range:         mean width of the intervals", ...
    "mis:           Mean Interval Score (alpha = " + tsx_format_num(1 - lv) + ")", ...
    "pinball_lower: pinball loss of the lower bound (quantile alpha / 2)", ...
    "pinball_upper: pinball loss of the upper bound (quantile 1 - alpha / 2)"];
cols = string(t.Properties.VariableNames);
cols = cols(cols ~= "forecast");
[~, pos] = ismember(cols, keys);
shown = notes(sort(pos));
shown = shown(shown ~= "");
out = tsx_cat_block(["Forecasting Results"; "Series " + x.series; tsx_period_text(x.dates)], ...
    shown(:), tsx_format_table(t(:, cols), [0, repmat(digits, 1, numel(cols) - 1)], ...
        "F#" + t.forecast, replace(cols, "bias_mae", "bias+mae")));
end
