function out = tsx_text_vident(x, digits)
%TSX_TEXT_VIDENT Text output of vident (print.tsx_vident in R).
import tsexplorer.internal.*
if isempty(digits)
    digits = 4;
end
t = x.table;
lines = tsx_format_table({t.lag, t.acf, tsx_signif_marks(t.acf ./ t.se_acf), t.q_lb, t.p_lb, ...
    t.pacf, tsx_signif_marks(t.pacf ./ t.se_pacf), t.q_mt, t.p_mt}, ...
    [0, digits, 0, digits, digits, digits, 0, digits, digits], [], ...
    ["Lag", "SACF", "", "LB", "P-value", "SPACF", "", "MT", "P-value"]);
out = tsx_cat_block("Univariate Sample ACF and PACF", ...
    ["LB: Ljung-Box Test"; "MT: Monti (1994) Test"; "H0: Process is white noise"; ...
     "Series " + x.series], lines);
end
