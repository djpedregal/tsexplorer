function tests = test_print_plot
% Tests of the text output (tsexplorer.print) and the plots (tsexplorer.plot),
% as the print/plot checks of the R tests.
tests = functiontests(localfunctions);
end

function setup(tc)
tc.TestData.fig = figure('Visible', 'off');
end

function teardown(tc)
close(tc.TestData.fig);
end

function test_print_returns_or_writes_the_lines(tc)
r = vident(tsxt_data("dla"), ncoef = 12);
lines = tsexplorer.print(r);
tc.verifyClass(lines, 'string');
tc.verifyTrue(any(contains(lines, "Univariate Sample ACF and PACF")));
tc.verifyTrue(any(contains(lines, "Ljung-Box")));
out = evalc('tsexplorer.print(r)');
tc.verifyEqual(strtrim(string(splitlines(strtrim(out)))), strtrim(lines));
% 12 lags plus the header, notes and rules
tc.verifyEqual(sum(startsWith(strtrim(lines), digitsPattern)), 12);
% the number of decimals can be changed
l2 = tsexplorer.print(r, digits = 2);
tc.verifyTrue(any(contains(l2, sprintf('%.2f', r.table.acf(1)))));
end

function test_print_of_every_class(tc)
[scc, ns] = tsxt_data("scc");
[lp, nl] = tsxt_data("lydia_pinkham");
dlp = vdif(log(lp));
a = tsxt_data("airpas");
dla = tsxt_data("dla");
la = tsxt_data("la");
f = tsxt_ref_input("sim_fc.csv");
cases = { ...
    sumstats(scc, names = ns), ["Mode:", "Kurtosis (-3):", "Correlation Matrix:"]; ...
    gausstest(scc), ["Bera-Jarque", "Multivariate Bera-Jarque"]; ...
    vident2(dlp, ncoef = 4, names = nl), ["Partial Lag Autocorrelation", "k=4 AIC="]; ...
    varsbc(dla, ncoef = 8), ["SBC(", "P-CHI"]; ...
    varsbc2(dla, ncoef = 8), "Minimum at lag"; ...
    vgranger(dlp, lags = 1:2, names = nl), "sales does not cause advertising"; ...
    vcusum(dla), "CUSUM and CUSUMSQ"; ...
    stdmean(a), "Least squares line"; ...
    testhet(a), ["Variance Ratio Tests", "Samples (1 - 48)"]; ...
    vboxcox(a), "Estimation of Box-Cox Lambdas:"; ...
    adftest(la, lags = 1:2), ["NO CONSTANT, NO TREND", "Phi3"]; ...
    vphillips(la, lags = 1:2), "Number of residual covs= "; ...
    johansentest(lp, lags = 2, names = nl), ["h= 0  -  h= 1", "Eigen1"]; ...
    nltests(dla, ncoef = 8), "Pe" + char(241) + "a & Rodriguez"; ...
    vtsay(dla, lags = 3), ["Tsay-F", "z(t-1)*z(t-3)"]; ...
    vbds(dla, maxdim = 3), "Distance as a fraction of the S.D.: 1.5"; ...
    vcumperiod(dla), "Band half width"; ...
    vspectrum(dla, smooth = 5), "Triangular window (5)"; ...
    vspectrum(dlp, series = [1 2], names = nl), "Cross spectrum: advertising - sales"; ...
    varspectrum(dla, order = 6), "AR Spectrum(6)"; ...
    vboxplot(a), "Box Plot (every 12 samples apart)"; ...
    vtboxplot(a), "Transpose Box Plot"; ...
    vscatter(scc, names = ns), "Intercept"; ...
    vhist(dla), "Histogram"; ...
    vqqplot(dla), "QQ plot"; ...
    faccuracy(la, f, stdpy = 0.03 * ones(12, 3), level = 0.9), ...
        ["bias+mae:      |bias| + mae", "(nominal 0.9)", "pinball_upper"]; ...
    fcompare(la, f), ["Squared Errors (MSE)", "Absolute Errors (MAE)", "F#1 vs F#2:"]};
for k = 1:size(cases, 1)
    lines = tsexplorer.print(cases{k, 1});
    for key = cases{k, 2}
        tc.verifyTrue(any(contains(lines, key)), cases{k, 1}.class(1) + ": " + key);
    end
end
% without intervals the interval measures are not shown
lines = tsexplorer.print(faccuracy(la, f));
tc.verifyFalse(any(contains(lines, ["coverage", "mis:"])));
tc.verifyFalse(any(contains(lines, "Percentage")));
% results without a text method show their fields
lines = tsexplorer.print(plotband(a));
tc.verifyEqual(lines(1), "<tsx_plotband>");
end

function test_text_tables_are_aligned(tc)
lines = tsexplorer.internal.tsx_format_table({[1; 22.5], ["a"; "bcd"], [NaN; Inf]}, [0, 0, 2], ...
    ["r1", "row2"], ["N", "S", "V"]);
% 22.5 with no decimals is 22, as in R (C's printf rounds half to even)
tc.verifyEqual(lines, ["       N    S    V"; "r1     1    a   NA"; "row2  22  bcd  Inf"]);
block = tsexplorer.internal.tsx_cat_block("Title", "note", lines);
tc.verifyEqual(strlength(block(1)), 40);
tc.verifyEqual(block(2), "Title");
end

function test_plots_of_every_class(tc)
[scc, ns] = tsxt_data("scc");
[lp, nl] = tsxt_data("lydia_pinkham");
dlp = vdif(log(lp));
[a, ~, da] = load_data("airpas");
dla = tsxt_data("dla");
la = tsxt_data("la");
f = tsxt_ref_input("sim_fc.csv");
% result, number of axes, text expected in a title
cases = { ...
    plotband(timetable(da, a)), 1, "2*S.D. bands"; ...
    plotband(a, overlay = true), 1, "every 12 samples"; ...
    plotband(scc, series = "all", standard = true), 1, "Standardised Plot"; ...
    vboxplot(timetable(da, a), highlight = 2), 1, "Box Plot"; ...
    vtboxplot(a), 1, "Transpose Box Plot"; ...
    vscatter(scc, names = ns), 1, "Scatter Plot: Series y1 vs y2"; ...
    vscatter(scc, series = "all"), 9, ""; ...
    vhist(dla), 1, "Histogram"; ...
    vqqplot(dla), 1, "Empirical Quantiles"; ...
    vident(dla), 2, "Univariate Sample Autocorrelation"; ...
    varsbc(dla, ncoef = 8), 2, "Information Criteria"; ...
    varsbc2(dla, ncoef = 8), 1, "SBC Criterion"; ...
    vcusum(dla), 2, "CUSUMSQ"; ...
    stdmean(a, type = 1), 1, "MEDA - Median Plot"; ...
    vboxcox(a), 1, "L-Lik"; ...
    nltests(dla, ncoef = 8), 2, "Squared Data"; ...
    vcumperiod(dla), 1, "Cumulative Periodogram"; ...
    vspectrum(dla, smooth = 3), 1, "Smoothed Spectrum"; ...
    vspectrum(dlp, series = [1 2], smooth = 3), 2, "Coherence"; ...
    varspectrum(dla), 1, "AR Spectrum(16)"; ...
    tsexplorer.fplot(la, f, stdpy = 0.03 * ones(12, 3), forecast = "all"), 2, "confidence bands"};
for k = 1:size(cases, 1)
    clf(tc.TestData.fig);
    figure(tc.TestData.fig);
    fig = tsexplorer.plot(cases{k, 1});
    tc.verifyEqual(fig, tc.TestData.fig);
    ax = findobj(fig, 'Type', 'axes');
    tc.verifyEqual(numel(ax), cases{k, 2}, cases{k, 1}.class(1));
    if cases{k, 3} ~= ""
        titles = title_text(ax);
        tc.verifyTrue(any(contains(titles, cases{k, 3})), cases{k, 1}.class(1));
    end
end
% vident2: ACF of one series or cross correlations of two
r = vident2(dlp, ncoef = 6, names = nl);
figure(tc.TestData.fig);
tsexplorer.plot(r, series = [1 2]);
ax = findobj(tc.TestData.fig, 'Type', 'axes');
titles = title_text(ax);
tc.verifyTrue(any(startsWith(titles, "CCF between advertising(t) and sales(t-k)")));
tc.verifyEqual(ax(1).XLim, [-7, 7]);
tsexplorer.plot(r, series = "sales");
ax = findobj(tc.TestData.fig, 'Type', 'axes');
tc.verifyTrue(any(contains(title_text(ax), "Series sales")));
tc.verifyError(@() tsexplorer.plot(r, series = 3), 'tsexplorer:series');
% classes without a plot
tc.verifyError(@() tsexplorer.plot(adftest(la, lags = 1)), 'tsexplorer:plot');
end

function t = title_text(ax)
% titles of the axes (also the title of a tiled layout)
t = strings(numel(ax), 1);
for k = 1:numel(ax)
    t(k) = strjoin(string(ax(k).Title.String), " ");
end
lay = findobj(ancestor(ax(1), 'figure'), 'Type', 'tiledlayout');
for k = 1:numel(lay)
    t(end + 1) = strjoin(string(lay(k).Title.String), " "); %#ok<AGROW>
end
end
